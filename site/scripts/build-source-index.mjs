// Writes planning/SOURCE_INDEX.md: every heading and slide title in the curriculum with its line number,
// so a lesson author can read exact line ranges instead of whole files. Run: npm run source-index
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../OrbitRoboticsCurriculum');
const target = join(here, '../../planning/SOURCE_INDEX.md');
if (!existsSync(root)) {
  console.log('Curriculum folder not found; nothing to index.');
  process.exit(0);
}

/** @returns {string[]} */
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return ['assignment', 'solution', 'repos', '.git', 'v0'].includes(name) ? [] : walk(p);
    return /(LAB_MANUAL|slides|curriculum_plan)\.md$/.test(name) ? [p] : [];
  });
}

const num = (p) => +(p.match(/Session (\d+)/)?.[1] ?? 0);
const files = walk(root).sort((a, b) => num(a) - num(b) || a.localeCompare(b));
let md = '# Source index (generated by `npm run source-index`; do not edit)\n\nFormat: `line  heading`. Read a section with its line range.\n';
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n');
  md += `\n## ${relative(root, f)} (${lines.length} lines)\n\`\`\`\n`;
  let inCode = false;
  lines.forEach((l, i) => {
    if (l.startsWith('```')) inCode = !inCode;
    if (!inCode && /^#{1,3} /.test(l)) md += `${String(i + 1).padStart(5)}  ${l}\n`;
  });
  md += '```\n';
}
writeFileSync(target, md);
console.log(`Indexed ${files.length} files → planning/SOURCE_INDEX.md`);
